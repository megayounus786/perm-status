def load_json(path: str, default=None):
    if not os.path.exists(path):
        return default
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def save_json(path: str, obj) -> None:
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(obj, f, separators=(",", ":"), ensure_ascii=False)
    os.replace(tmp, path)


def select_members(root: str, reg: dict, top: int) -> Tuple[dict, List[str]]:
    """Top-N by PERM volume from the index; ties broken by total filings, then name.
    Existing members keep their slug; new members get a collision-free slug."""
    idx = load_json(os.path.join(root, INDEX_REL))
    emps = idx["employers"]
    ranked = sorted(emps, key=lambda e: (-(e.get("perm") or 0), -(e.get("total") or 0), (e.get("n") or "").lower()))
    members = reg.setdefault("employers", [])
    by_name = {m["name"]: m for m in members}
    used = {m["slug"] for m in members}
    added: List[str] = []
    for rank, e in enumerate(ranked[:top], 1):
        name = e["n"]
        if name in by_name:
            continue
        slug = normalize_slug(name)
        base, k = slug, 2
        while slug in used:
            slug = f"{base}-{k}"
            k += 1
        used.add(slug)
        m = {"slug": slug, "name": name, "a": e.get("a"), "addedAt": today_et().isoformat(), "addedRank": rank}
        members.append(m)
        by_name[name] = m
        added.append(slug)
    reg["selection"] = {"top": top, "rule": "employer_index.json `perm` desc (DOL OFLC PERM disclosure FY2008–FY2026, cert+denied+withdrawn), ties: total filings desc, then name",
                        "selectedAt": dt.datetime.now(ET).isoformat(timespec="seconds"), "indexGeneratedAt": idx.get("generatedAt")}
    return reg, added


