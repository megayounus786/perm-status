def refresh(reg: dict, probe_all: bool = False) -> dict:
    members = reg["employers"]
    with cf.ThreadPoolExecutor(max_workers=FETCH_WORKERS) as ex:
        results = list(ex.map(lambda m: fetch_employer(m, probe_all), members))
    ok = 0
    for m, upd in zip(members, results):
        errs = upd.pop("fetchErrors", [])
        if "h1b" in upd:
            ok += 1
        for k, v in upd.items():
            m[k] = v
        m["fetchErrors"] = errs
    st, meta = fetch_with_retry(f"{API_BASE}/api/meta")
    if st == 200 and isinstance(meta, dict):
        reg["liveMeta"] = meta
    reg["refreshedAt"] = dt.datetime.now(ET).isoformat(timespec="seconds")
    reg["refreshStats"] = {"members": len(members), "h1bOk": ok, "errors": sum(1 for m in members if m.get("fetchErrors"))}
    return reg


