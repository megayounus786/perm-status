def http_json(url: str, timeout: int = FETCH_TIMEOUT) -> Tuple[int, Any]:
    req = urllib.request.Request(url, headers={"User-Agent": UA, "Accept": "application/json"})
    try:
        with urllib.request.urlopen(req, timeout=timeout) as r:
            return r.status, json.loads(r.read().decode("utf-8"))
    except urllib.error.HTTPError as e:
        try:
            body = json.loads(e.read().decode("utf-8"))
        except Exception:
            body = None
        return e.code, body


def fetch_with_retry(url: str, tries: int = 3) -> Tuple[int, Any]:
    last: Tuple[int, Any] = (0, None)
    for i in range(tries):
        try:
            last = http_json(url)
        except Exception as e:  # network / timeout
            last = (0, {"error": str(e)})
        if last[0] in (200, 404):
            return last
    return last


def trim_h1b(h: dict) -> dict:
    """Keep only what the pages render (keeps the registry small and stable)."""
    def yr(y, keys):
        return {k: y.get(k) for k in keys if k in y}
    out = {
        "slug": h.get("slug"), "name": h.get("name"), "fy": h.get("fy"),
        "total": h.get("total"), "wage_median_all": h.get("wage_median_all"),
        "aliasNames": [a for a in (h.get("aliasNames") or []) if a][:8],
        "memberSlugs": list(h.get("memberSlugs") or []),
        "partialFYs": list(h.get("partialFYs") or []),
        "permByYear": [yr(y, ("fy", "cert", "denied", "withdrawn", "salary_median", "partial")) for y in (h.get("permByYear") or [])],
        "lcaByYear": [yr(y, ("fy", "cert", "denied", "withdrawn", "total", "wage_median", "pw_median", "partial")) for y in (h.get("lcaByYear") or [])],
        "socs": [yr(s, ("soc", "title", "n", "wage_median", "wage_p10", "wage_p90", "pw_median")) for s in sorted(h.get("socs") or [], key=lambda s: -(s.get("n") or 0))[:10]],
        "permTitlesAll": [yr(t, ("title", "n")) for t in (h.get("permTitlesAll") or [])[:10]],
        "salaryTrend": [yr(y, ("fy", "h1b_offered", "prevailing", "gc", "partial")) for y in (h.get("salaryTrend") or [])],
    }
    return out


def trim_live(l: dict) -> dict:
    return {
        "name": l.get("name"), "total": l.get("total"), "statuses": dict(l.get("statuses") or {}),
        "certified": l.get("certified"), "denied": l.get("denied"),
        "firstFiling": l.get("firstFiling"), "lastFiling": l.get("lastFiling"),
        "topTitles": [{"title": t.get("title"), "count": t.get("count")} for t in (l.get("topTitles") or [])[:10]],
    }


def fetch_employer(entry: dict, probe_all: bool) -> dict:
    """Fetch h1b + live payloads for one registry entry. Returns a dict of updates
    (never raises; on failure the caller keeps the stored payloads)."""
    upd: Dict[str, Any] = {"fetchErrors": []}
    name_slug = normalize_slug(entry["name"])
    st, h = fetch_with_retry(f"{API_BASE}/api/employers/{name_slug}/h1b")
    if st == 200 and isinstance(h, dict) and "permByYear" in h:
        upd["h1b"] = trim_h1b(h)
        upd["h1bSlug"] = h.get("slug") or name_slug
    else:
        upd["fetchErrors"].append(f"h1b {st}")
    h1b = upd.get("h1b") or entry.get("h1b") or {}
    # Live tracker: keyed by the scanner's own name slugs. Probe the canonical,
    # the name slug and every member slug once; afterwards only the slug that hit.
    if probe_all or not entry.get("liveSlugs"):
        cands: List[str] = []
        for c in [name_slug, h1b.get("slug"), entry.get("a")] + list(h1b.get("memberSlugs") or []):
            c = normalize_slug(c or "")
            if c and c not in cands:
                cands.append(c)
    else:
        cands = list(entry["liveSlugs"])
    hits: List[Tuple[str, dict]] = []
    for c in cands:
        st, l = fetch_with_retry(f"{API_BASE}/api/employers/{c}")
        if st == 200 and isinstance(l, dict) and "statuses" in l:
            hits.append((c, l))
        elif st != 404:
            upd["fetchErrors"].append(f"live {c} {st}")
    if hits:
        # The scanner keys cases by the exact employer_name string, so reunified
        # name variants are disjoint case sets: merge them (sum statuses, union
        # titles, min/max filing dates) the same way the store merges permByYear.
        hits.sort(key=lambda h: -(h[1].get("total") or 0))
        merged = trim_live(hits[0][1])
        merged["variants"] = [{"slug": c, "name": l.get("name"), "total": l.get("total")} for c, l in hits]
        if len(hits) > 1:
            statuses: Dict[str, int] = {}
            titles: Dict[str, int] = {}
            firsts, lasts = [], []
            for _, l in hits:
                for k, v in (l.get("statuses") or {}).items():
                    statuses[k] = statuses.get(k, 0) + (v or 0)
                for t in l.get("topTitles") or []:
                    if t.get("title"):
                        titles[t["title"].strip()] = titles.get(t["title"].strip(), 0) + (t.get("count") or 0)
                if l.get("firstFiling"):
                    firsts.append(l["firstFiling"])
                if l.get("lastFiling"):
                    lasts.append(l["lastFiling"])
            merged.update({
                "total": sum((l.get("total") or 0) for _, l in hits), "statuses": statuses,
                "certified": statuses.get("CERTIFIED", 0), "denied": statuses.get("DENIED", 0),
                "firstFiling": min(firsts) if firsts else "", "lastFiling": max(lasts) if lasts else "",
                "topTitles": [{"title": t, "count": c} for t, c in sorted(titles.items(), key=lambda kv: -kv[1])[:10]],
            })
        upd["liveSlug"] = hits[0][0]
        upd["liveSlugs"] = [c for c, _ in hits]
        upd["live"] = merged
        upd["liveHits"] = len(hits)
    elif not upd["fetchErrors"]:
        upd["live"] = None  # genuinely no live entry (all 404)
        upd["liveSlug"] = None
        upd["liveSlugs"] = []
    return upd


