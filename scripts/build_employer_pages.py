def perm_stats(h1b: dict) -> dict:
    """Port of employer.html permStatsFromDisclosure()."""
    cert = den = wd = 0
    fys = []
    for y in h1b.get("permByYear") or []:
        cert += y.get("cert") or 0
        den += y.get("denied") or 0
        wd += y.get("withdrawn") or 0
        if y.get("fy"):
            fys.append(y["fy"])
    fys.sort()
    total = cert + den + wd
    adj = cert + den
    return {"cert": cert, "denied": den, "withdrawn": wd, "total": total, "adjudicated": adj,
            "rate": pct(cert, adj) if adj else None,
            "firstFy": fys[0] if fys else None, "lastFy": fys[-1] if fys else None}


def live_stats(live: Optional[dict]) -> dict:
    if not live:
        return {"tracked": 0, "pending": 0, "certified": 0, "denied": 0, "withdrawn": 0, "rfi": 0, "audit": 0, "rate": None, "statuses": {}}
    s = live.get("statuses") or {}
    cert = s.get("CERTIFIED", 0) + s.get("CERTIFIED - EXPIRED", 0)
    den = s.get("DENIED", 0)
    wd = s.get("WITHDRAWN", 0)
    rfi = s.get("RFI ISSUED", 0)
    ar = s.get("ANALYST REVIEW", 0)
    audit = s.get("AUDIT REVIEW", 0) + s.get("PENDING AUDIT RESPONSE", 0) + s.get("SUPERVISED RECRUITMENT", 0)
    pending = ar + rfi + audit
    tracked = sum(v for v in s.values() if isinstance(v, int))
    return {"tracked": tracked, "pending": pending, "certified": cert, "denied": den, "withdrawn": wd,
            "rfi": rfi, "ar": ar, "audit": audit, "rate": pct(cert, cert + den) if (cert + den) else None,
            "statuses": s, "first": live.get("firstFiling") or "", "last": live.get("lastFiling") or ""}


def above_pw_pct(h1b: dict) -> Optional[int]:
    above = cmp = 0
    for s in h1b.get("socs") or []:
        if s.get("wage_median") is not None and s.get("pw_median"):
            cmp += s.get("n") or 0
            if s["wage_median"] >= s["pw_median"]:
                above += s.get("n") or 0
    return int(round(above / cmp * 100)) if cmp else None


def fingerprint(m: dict, extras_entry: Optional[dict] = None) -> str:
    """Hash of everything that changes a page's numbers (worker data, rank, offline extras)."""
    core = {k: m.get(k) for k in ("name", "rank", "perm", "lca", "total", "h1b", "live")}
    core["extras"] = extras_entry
    return hashlib.sha1(json.dumps(core, sort_keys=True, separators=(",", ":")).encode()).hexdigest()[:16]


