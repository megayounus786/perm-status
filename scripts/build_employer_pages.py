# ── sitemap + employer.html blocks ───────────────────────────────────────────
def sitemap_block(members: List[dict], hub_lastmod: str) -> str:
    out = [f"\n  <url>\n    <loc>{SITE}/employers</loc>\n    <lastmod>{hub_lastmod}</lastmod>\n    <changefreq>daily</changefreq>\n    <priority>0.8</priority>\n  </url>"]
    for m in sorted(members, key=lambda m: (m.get("rank") or 10**9, m["slug"])):
        out.append(f"\n  <url>\n    <loc>{SITE}/employers/{m['slug']}</loc>\n    <lastmod>{m.get('lastmod') or hub_lastmod}</lastmod>\n    <changefreq>weekly</changefreq>\n    <priority>0.6</priority>\n  </url>")
    return "".join(out) + "\n  "


def employer_html_block(members: List[dict]) -> str:
    """JSON map of {canonical h1b slug | name slug: static slug} for employer.html."""
    mp: Dict[str, str] = {}
    for m in members:
        for k in (m.get("h1bSlug"), normalize_slug(m["name"]), m.get("liveSlug")):
            if k:
                mp[k] = m["slug"]
    return '\n<script id="il-static-employers" type="application/json">' + json.dumps(mp, sort_keys=True, separators=(",", ":")) + "</script>\n"


# ── orchestration ────────────────────────────────────────────────────────────
def dashboard_ctx(root: str) -> dict:
    D = load_json(os.path.join(root, DASH_REL))
    dol = D["dol"]
    mm = re.search(r"'(\d\d)", dol.get("label", ""))
    yr = ("20" + mm.group(1)) if mm else ""
    return {"frontier": dol["monthFull"] + (f" {yr}" if yr else ""), "pct": f"{dol['pctProcessed']}%",
            "remain": n(dol["casesRemaining"]), "avg": str(D["avgDays"]["current"]), "avgCert": str(D["avgDays"]["certified"]),
            "pending": n(D["backlog"]["total"]), "updated": fmt_et_long(D["updatedAt"])}


def render_all(root: str, reg: dict, check: bool = False) -> List[str]:
    members = reg["employers"]
    top_n = (reg.get("selection") or {}).get("top") or DEFAULT_TOP
    # lastmod: today when the page's data changed vs the committed snapshot, else keep
    today = today_et().isoformat()
    extras_all = load_json(os.path.join(root, EXTRAS_REL)) or {}
    for m in members:
        fp = fingerprint(m, (extras_all.get("employers") or {}).get(m["slug"]))
        if m.get("fingerprint") != fp or not m.get("lastmod"):
            m["fingerprint"], m["lastmod"] = fp, today
    for m in members:  # the figure every page/hub row shows (same source as the interactive profile)
        m["permSum"] = perm_stats(m.get("h1b") or {})["total"]
    ranked = sorted([m for m in members if m.get("rank")], key=lambda m: m["rank"])
    related: Dict[str, List[dict]] = {}
    for i, m in enumerate(ranked):
        neigh = [ranked[j] for j in range(max(0, i - 3), min(len(ranked), i + 4)) if j != i]
        related[m["slug"]] = neigh[:6]
    # "Page updated" is stamped to the day (not the minute) so re-rendering the same
    # data is a byte-for-byte no-op — no spurious file churn on every deploy.
    ctx = {"dash": dashboard_ctx(root), "index": reg.get("index") or {}, "liveMeta": reg.get("liveMeta") or {},
           "extras": extras_all, "related": related, "topN": top_n,
           "widgets": shared_widgets(root), "generated": today_et().strftime("%b %-d, %Y")}
    outputs: Dict[str, str] = {}
    for m in members:
        outputs[os.path.join(OUT_DIR, m["slug"] + ".html")] = build_page(m, ctx)
    outputs[HUB_REL] = build_hub(members, ctx)
    # sitemap + employer.html blocks
    sm_path = os.path.join(root, "sitemap.xml")
    sm = open(sm_path, encoding="utf-8").read()
    if "<!--il-ssr:employers-->" not in sm:
        sm = sm.replace("</urlset>", "  <!--il-ssr:employers--><!--/il-ssr:employers-->\n</urlset>")
    hub_lastmod = max([m["lastmod"] for m in members] + [today])
    outputs["sitemap.xml"] = sub_marked(sm, "employers", sitemap_block(members, hub_lastmod))
    eh_path = os.path.join(root, "employer.html")
    eh = open(eh_path, encoding="utf-8").read()
    if "<!--il-ssr:static-employers-->" in eh:
        outputs["employer.html"] = sub_marked(eh, "static-employers", employer_html_block(members))
    changed = []
    for rel, content in outputs.items():
        p = os.path.join(root, rel)
        old = open(p, encoding="utf-8").read() if os.path.exists(p) else None
        if old != content:
            changed.append(rel)
            if not check:
                os.makedirs(os.path.dirname(p) or ".", exist_ok=True)
                tmp = p + ".render.tmp"
                with open(tmp, "w", encoding="utf-8") as f:
                    f.write(content)
                os.replace(tmp, p)
    return changed


def deploy_step(root: str, check: bool = False) -> str:
    """Called by render_live.py at deploy time: refresh from the worker (per-employer
    fallback to the committed snapshot) and re-render. Returns a one-line summary."""
    reg_path = os.path.join(root, REGISTRY_REL)
    reg = load_json(reg_path)
    if not reg or not reg.get("employers"):
        return "employer pages: no registry — skipped"
    apply_index(root, reg)
    reg = refresh(reg)
    changed = render_all(root, reg, check=check)
    if not check:
        save_json(reg_path, reg)
    rs = reg.get("refreshStats") or {}
    pages = sum(1 for c in changed if c.startswith(OUT_DIR + "/"))
    return (f"employer pages: {len(reg['employers'])} members · worker ok {rs.get('h1bOk')}/{rs.get('members')} "
            f"({rs.get('errors')} with fetch errors → snapshot fallback) · {'would change' if check else 'rendered'} {pages} page(s) + {len(changed) - pages} other file(s)")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    ap.add_argument("--select", action="store_true")
    ap.add_argument("--refresh", action="store_true")
    ap.add_argument("--render", action="store_true")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--probe-all", action="store_true", help="re-probe every live-tracker slug candidate")
    ap.add_argument("--top", type=int, default=DEFAULT_TOP)
    a = ap.parse_args()
    root = a.root
    reg_path = os.path.join(root, REGISTRY_REL)
    reg = load_json(reg_path, {"version": 1, "employers": []})
    if a.select:
        reg, added = select_members(root, reg, a.top)
        print(f"select: {len(reg['employers'])} members ({len(added)} added)")
    apply_index(root, reg)
    if a.refresh:
        reg = refresh(reg, probe_all=a.probe_all or a.select)
        rs = reg["refreshStats"]
        print(f"refresh: h1b ok {rs['h1bOk']}/{rs['members']}, {rs['errors']} with errors; live entries {sum(1 for m in reg['employers'] if m.get('live'))}")
    if a.render:
        changed = render_all(root, reg, check=a.check)
        print(f"render: {'would change' if a.check else 'wrote'} {len(changed)} file(s)")
    if not a.check and (a.select or a.refresh or a.render):
        save_json(reg_path, reg)
        print(f"saved {REGISTRY_REL}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
