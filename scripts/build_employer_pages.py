def sub_marked(text: str, name: str, inner: str) -> str:
    pat = rf"(<!--il-ssr:{re.escape(name)}-->).*?(<!--/il-ssr:{re.escape(name)}-->)"
    new, cnt = re.subn(pat, lambda m: m.group(1) + inner + m.group(2), text, count=1, flags=re.S)
    if cnt != 1:
        raise RuntimeError(f"marker not found: {name}")
    return new


